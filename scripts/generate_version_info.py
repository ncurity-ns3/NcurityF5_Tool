"""Write PyInstaller Windows version resource (packaging/file_version_info.txt)."""

from __future__ import annotations

import re
from pathlib import Path


def _read_version(root: Path) -> tuple[str, int, int, int, int]:
    text = (root / "pyproject.toml").read_text(encoding="utf-8")
    match = re.search(r'^version\s*=\s*"([^"]+)"', text, re.MULTILINE)
    version = match.group(1) if match else "1.1.0"
    parts = (version.split(".") + ["0", "0", "0"])[:4]
    nums = tuple(int(part) for part in parts)
    # The fourth number is the Windows installer revision. Raise
    # packaging/windows_revision.txt so a same 1.3.1 package replaces the exe.
    if version.count(".") == 2:
        nums = (nums[0], nums[1], nums[2], _windows_revision(root))
    return version, nums


def _windows_revision(root: Path) -> int:
    path = root / "packaging" / "windows_revision.txt"
    if not path.exists():
        return 1
    text = path.read_text(encoding="utf-8").strip()
    return int(text) if text.isdigit() else 1


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    version, (major, minor, patch, build) = _read_version(root)
    out = root / "packaging" / "file_version_info.txt"
    out.parent.mkdir(parents=True, exist_ok=True)
    content = f"""# UTF-8
# Generated by scripts/generate_version_info.py — do not edit by hand.

VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({major}, {minor}, {patch}, {build}),
    prodvers=({major}, {minor}, {patch}, {build}),
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          "040904B0",
          [
            StringStruct("CompanyName", "Ncurity"),
            StringStruct("FileDescription", "Ncurity F5 Big-IP Managing Tool"),
            StringStruct("FileVersion", "{version}"),
            StringStruct("InternalName", "NcurityF5Tool"),
            StringStruct("LegalCopyright", "Copyright (C) Ncurity"),
            StringStruct("OriginalFilename", "NcurityF5Tool.exe"),
            StringStruct("ProductName", "Ncurity F5 Big-IP Managing Tool"),
            StringStruct("ProductVersion", "{version}"),
          ],
        )
      ]
    ),
    VarFileInfo([VarStruct("Translation", [1033, 1200])]),
  ],
)
"""
    out.write_text(content, encoding="utf-8")
    print(f"Wrote {out} (version {version})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
